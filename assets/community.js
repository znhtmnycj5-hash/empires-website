(function(){
'use strict';
(async function(){
  try{
    await window.EMPIRE_AUTH.init();
    const auth=window.EMPIRE_AUTH;

    const setCount=(key,value)=>{
      const el=document.querySelector('[data-site-count="'+key+'"]');
      if(el)el.textContent=String(value);
    };

    const updateHeader=()=>{
      const link=document.querySelector('a.login');
      if(link){
        if(auth.user){
          link.textContent='♙ Выйти из профиля';
          link.title='Выйти из профиля';
          link.href='#';
          link.dataset.authSignout='1';
        }else{
          link.textContent='♙ Войти в сообщество';
          link.title='';
          link.href='register.html';
          link.removeAttribute('data-auth-signout');
        }
      }
      document.querySelectorAll('a[href="#"]').forEach(a=>{
        if(a.textContent.trim()==='Найти полк')a.href='regiments.html';
      });
    };

    updateHeader();

    if(auth.user){
      await auth.touchPresence();
      setInterval(()=>auth.touchPresence(),60000);
    }

    try{
      const {count,error}=await auth.client.from('empire_profiles').select('id',{count:'exact',head:true});
      if(!error&&typeof count==='number')setCount('users',count);
    }catch(e){}

    try{
      const {count,error}=await auth.client.from('empire_regiments').select('id',{count:'exact',head:true});
      if(!error&&typeof count==='number')setCount('regiments',count);
    }catch(e){
      const local=document.querySelectorAll('.regiment-tile[data-regiment-name]').length;
      if(local)setCount('regiments',local);
    }

    if(location.pathname.endsWith('index.html')||location.pathname.endsWith('/')){
      try{
        const html=await fetch('battles.html',{cache:'no-store'}).then(r=>r.text());
        const doc=new DOMParser().parseFromString(html,'text/html');
        const count=doc.querySelectorAll('.battle-record').length;
        if(count)setCount('battles',count);
      }catch(e){}
      // Campaigns are currently generated by the community campaign module.
      // Keep the homepage value synchronized with the current campaign list once
      // the module is moved to the shared database.
      const campaignCountEl=document.querySelector('[data-site-count="campaigns"]');
      if(campaignCountEl&&campaignCountEl.textContent.trim()==='')campaignCountEl.textContent='0';
    }

    document.dispatchEvent(new CustomEvent('empire:community-ready'));
  }catch(error){
    console.warn('Empire community:',error);
  }
})();
})();